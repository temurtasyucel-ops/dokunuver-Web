revoke all on public.panel_orders from anon,authenticated;
grant select,insert,update on public.panel_orders to service_role;
grant usage,select on sequence public.panel_orders_order_no_seq to service_role;
create index if not exists panel_orders_status_idx on public.panel_orders(status,order_no desc);
create table if not exists public.panel_events (
 id bigint generated by default as identity primary key,
 entity text not null, ref text not null, action text not null,
 actor_id text, details jsonb not null default '{}'::jsonb,
 created_at timestamptz not null default now()
);
alter table public.panel_events enable row level security;
revoke all on public.panel_events from anon,authenticated;
grant select on public.panel_events to service_role;
create index if not exists panel_events_ref_idx on public.panel_events(entity,ref,id desc);
create or replace function public.panel_record_change() returns trigger
language plpgsql security definer set search_path=pg_catalog,public as $$
declare before_row jsonb; after_row jsonb; item jsonb; changed jsonb; actor text; headers jsonb;
begin
 before_row=case when TG_OP='INSERT' then '{}'::jsonb else to_jsonb(OLD) end;
 after_row=case when TG_OP='DELETE' then '{}'::jsonb else to_jsonb(NEW) end;
 if TG_OP='UPDATE' and before_row=after_row then return NEW; end if;
 item=case when TG_OP='DELETE' then before_row else after_row end;
 select coalesce(jsonb_agg(key),'[]'::jsonb) into changed from jsonb_object_keys(before_row||after_row) key
 where key not in ('created_at','updated_at','revision') and (before_row->key) is distinct from (after_row->key);
 if TG_OP='UPDATE' and changed='[]'::jsonb then return NEW; end if;
 headers=coalesce(nullif(current_setting('request.headers',true),''),'{}')::jsonb;
 actor=headers->>'x-panel-actor';
 insert into public.panel_events(entity,ref,action,actor_id,details)
 values(TG_TABLE_NAME,coalesce(item->>'code',item->>'id'),lower(TG_OP),actor,
 jsonb_strip_nulls(jsonb_build_object('fields',changed,'status',item->'status','active',item->'active','locked',item->'locked','order_no',item->'order_no')));
 if TG_OP='DELETE' then return OLD; else return NEW; end if;
end $$;
revoke all on function public.panel_record_change() from public,anon,authenticated;
do $$ declare t text; begin
 foreach t in array array['iban_cards','smart_links','site_content','panel_orders'] loop
  if to_regclass('public.'||t) is not null then
   execute format('drop trigger if exists panel_history on public.%I',t);
   execute format('create trigger panel_history after insert or update or delete on public.%I for each row execute function public.panel_record_change()',t);
  end if;
 end loop;
end $$;
create or replace function public.panel_set_card_active(p_kind text,p_codes text[],p_active boolean) returns integer
language plpgsql security definer set search_path=pg_catalog,public as $$
declare target text; row_data record; found_count integer=0; affected integer;
begin
 if p_kind is null or p_kind not in ('iban','smart') or p_active is null or p_codes is null or cardinality(p_codes) not between 1 and 100 then raise exception 'Invalid selection'; end if;
 if (select count(distinct c) from unnest(p_codes) c)<>cardinality(p_codes) or exists(select 1 from unnest(p_codes) c where c is null or c!~'^[A-Z0-9]{6}$') then raise exception 'Invalid codes'; end if;
 target=case when p_kind='iban' then 'iban_cards' else 'smart_links' end;
 for row_data in execute format('select code,status from public.%I where code=any($1) order by code for update',target) using p_codes loop
  found_count=found_count+1;
  if p_active and coalesce(row_data.status,'') not in ('assigned','locked') then raise exception 'Card is not assigned'; end if;
 end loop;
 if found_count<>cardinality(p_codes) then raise exception 'Missing card'; end if;
 execute format('update public.%I set active=$1 where code=any($2)',target) using p_active,p_codes;
 get diagnostics affected=row_count;
 return affected;
end $$;
revoke all on function public.panel_set_card_active(text,text[],boolean) from public,anon,authenticated;
grant execute on function public.panel_set_card_active(text,text[],boolean) to service_role;
notify pgrst,'reload schema';
commit;
