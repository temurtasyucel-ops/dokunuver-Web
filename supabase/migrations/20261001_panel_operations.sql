create table if not exists public.panel_orders (
 id uuid primary key default gen_random_uuid(),
 order_no bigint generated by default as identity unique,
 customer_name text not null check(char_length(customer_name) between 1 and 120),
 phone text not null default '' check(char_length(phone)<=40),
 notes text not null default '' check(char_length(notes)<=2000),
 tracking text not null default '' check(char_length(tracking)<=200),
 delivery_method text not null check(delivery_method in ('courier','pickup')),
 status text not null default 'new' check(status in ('new','preparing','ready','shipped','delivered','cancelled')),
 items jsonb not null check(jsonb_typeof(items)='array' and jsonb_array_length(items) between 1 and 30),
 shipping_fee numeric(12,2) not null default 0 check(shipping_fee>=0),
 total numeric(14,2) not null check(total>=0),
 revision bigint not null default 1 check(revision>0),
 created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
